import { test, expect } from '@playwright/test'
test('projects and tasks support complete CRUD and deep links', async ({ page }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Всё под контролем' })).toBeVisible()
  await page.getByRole('button', { name: 'Добавить проект', exact: true }).click()
  await page.getByLabel('Название проекта', { exact: true }).fill('Release checklist')
  await page.getByRole('button', { name: 'Сохранить проект' }).click()
  await page.getByRole('navigation').getByRole('link', { name: /Release checklist/ }).click()
  await page.getByRole('button', { name: '+ Новая задача', exact: true }).click()
  await page.getByLabel('Название задачи', { exact: true }).fill('Prepare release')
  await page.getByLabel('Описание', { exact: true }).fill('Run all checks and publish.')
  await page.getByRole('button', { name: 'Сохранить задачу' }).click()
  await expect(page.getByRole('link', { name: 'Prepare release', exact: true })).toBeVisible()
  await page.getByLabel('Статус: Prepare release').selectOption('done')
  await expect(page.getByLabel('Статус: Prepare release')).toHaveValue('done')
  await page.getByRole('link', { name: 'Prepare release', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Prepare release', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Редактировать задачу', exact: true }).click()
  await page.getByLabel('Название задачи', { exact: true }).fill('Release ready')
  await page.getByRole('button', { name: 'Сохранить задачу' }).click()
  await expect(page.getByRole('heading', { name: 'Release ready', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить задачу', exact: true }).click()
  await page.getByRole('button', { name: 'Подтвердить удаление' }).click()
  await expect(page.getByRole('heading', { name: 'Release checklist', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить проект', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить с задачами' }).click()
  await expect(page.getByRole('navigation').getByRole('link', { name: /Release checklist/ })).toHaveCount(0)
})
